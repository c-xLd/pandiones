/**
 * Local development only: a test admin for checking the panel in the browser against the local
 * database (npm run db:dev). Refuses any DATABASE_URL that is not on loopback.
 *
 *   npx tsx scripts/dev-test-admin.ts          create/refresh the account; credentials go to .env.test-admin.local (git-ignored)
 *   npx tsx scripts/dev-test-admin.ts --code   print the current 2FA code for that account
 */
import crypto from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { PrismaClient } from '@prisma/client';
import { encryptSecret } from '../src/lib/security/crypto';
import { generateTotpSecret, totpAt } from '../src/lib/security/totp';
import { hashPassword } from '../src/lib/auth/password-policy';

const FILE = '.env.test-admin.local';
const EMAIL = 'admin-dev@pandiones.test';

const url = process.env.DATABASE_URL ?? '';
if (!/@(127\.0\.0\.1|localhost)(:\d+)?\//.test(url)) {
  console.error('Yalnız yerel veritabanında çalışır (DATABASE_URL loopback olmalı).');
  process.exit(1);
}

async function main() {
  if (process.argv.includes('--code')) {
    const secret = /TEST_ADMIN_TOTP=(\S+)/.exec(readFileSync(FILE, 'utf8'))?.[1];
    if (!secret) throw new Error(`${FILE} içinde TOTP yok; önce betiği parametresiz çalıştırın.`);
    console.log(totpAt(secret, Date.now()));
    return;
  }
  const db = new PrismaClient();
  try {
    const password = crypto.randomBytes(18).toString('base64url');
    const secret = generateTotpSecret();
    const data = { name: 'Yerel Test Yöneticisi', role: 'ADMIN', passwordHash: await hashPassword(password), emailVerifiedAt: new Date(), totpSecret: encryptSecret(secret), totpEnabledAt: new Date(), totpLastStep: null, failedLoginCount: 0, lockedUntil: null };
    await db.user.upsert({ where: { email: EMAIL }, create: { email: EMAIL, ...data }, update: data });
    writeFileSync(FILE, `# Local test admin (local database only). Regenerated by scripts/dev-test-admin.ts\nTEST_ADMIN_EMAIL=${EMAIL}\nTEST_ADMIN_PASSWORD=${password}\nTEST_ADMIN_TOTP=${secret}\n`);
    console.log(`Test yöneticisi hazır; bilgiler ${FILE} dosyasında.`);
  } finally {
    await db.$disconnect();
  }
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
